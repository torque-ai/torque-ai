function parseFactoryTimestampMs(value) {
  if (!value) return Number.NaN;
  if (value instanceof Date) return value.getTime();
  const text = String(value).trim();
  if (!text) return Number.NaN;
  const normalized = SQLITE_UTC_TIMESTAMP_PATTERN.test(text)
    ? `${text.replace(' ', 'T')}Z`
    : text;
  return Date.parse(normalized);
}

function getNeedsReplanCooldownInfo(item, nowMs = Date.now()) {
  if (!item || item.status !== 'needs_replan') {
    return { active: false, updatedAtMs: Number.NaN, remainingMs: 0 };
  }
  const updatedAtMs = parseFactoryTimestampMs(item.updated_at);
  if (!Number.isFinite(updatedAtMs)) {
    return { active: false, updatedAtMs, remainingMs: 0 };
  }
  const remainingMs = NEEDS_REPLAN_COOLDOWN_MS - (nowMs - updatedAtMs);
  return {
    active: remainingMs > 0,
    updatedAtMs,
    remainingMs: Math.max(0, remainingMs),
  };
}

function buildNeedsReplanPenaltyEvidence(item) {
  const origin = getWorkItemOriginObject(item);
  const evidenceParts = [
    item?.reject_reason,
    origin?.last_rejection_reason,
    origin?.last_gate_feedback,
  ];

  if (origin?.last_rejection_details) {
    evidenceParts.push(JSON.stringify(origin.last_rejection_details));
  }
  if (origin?.last_plan_description_quality_rejection) {
    evidenceParts.push(JSON.stringify(origin.last_plan_description_quality_rejection));
  }
  if (Array.isArray(origin?.escalation_history)) {
    evidenceParts.push(origin.escalation_history
      .map((entry) => entry && entry.reason)
      .filter(Boolean)
      .join('\n'));
  }

  return {
    evidence: evidenceParts.filter(Boolean).join('\n'),
    historyCount: Array.isArray(origin?.escalation_history) ? origin.escalation_history.length : 0,
  };
}

function getNeedsReplanSelectionPenalty(item) {
  if (!item || item.status !== 'needs_replan') {
    return { penalty: 0, label: null };
  }

  const { evidence, historyCount } = buildNeedsReplanPenaltyEvidence(item);
  if (!evidence.trim()) {
    return { penalty: 0, label: null };
  }

  let penalty = 0;
  let label = null;
  if (NEEDS_REPLAN_PLAN_QUALITY_PENALTY_PATTERN.test(evidence)) {
    penalty = NEEDS_REPLAN_PLAN_QUALITY_SELECTION_PENALTY;
    label = 'plan_quality_or_noop_rejection';
  } else if (NEEDS_REPLAN_GENERIC_REJECTION_PENALTY_PATTERN.test(evidence)) {
    penalty = NEEDS_REPLAN_GENERIC_REJECTION_SELECTION_PENALTY;
    label = 'prior_replan_rejection';
  }

  if (penalty > 0 && historyCount > 1) {
    penalty += Math.min(
      NEEDS_REPLAN_HISTORY_PENALTY_MAX,
      (historyCount - 1) * NEEDS_REPLAN_HISTORY_PENALTY_STEP
    );
  }

  return { penalty, label };
}

function getPlanQualityReplanAttemptCount(item, origin = getWorkItemOriginObject(item) || {}) {
  const attempts = [
    origin?.plan_gen_attempts,
    origin?.last_rejection_attempt,
  ]
    .map((value) => Number(value))
    .filter((value) => Number.isFinite(value));

  return attempts.length > 0 ? Math.max(...attempts) : 0;
}

function shouldEscalatePlanQualityAttemptWindow({ reasonShape, attempt, origin = {} } = {}) {
  if (!PLAN_QUALITY_ESCALATION_REASON_SHAPES.has(reasonShape)) {
    return false;
  }

  const attemptCount = Number(attempt);
  if (!Number.isFinite(attemptCount) || attemptCount < SAME_SHAPE_THRESHOLD) {
    return false;
  }

  const lastEscalation = origin?.last_escalation;
  return !(lastEscalation
    && lastEscalation.kind === 'provider_switch'
    && lastEscalation.reason_shape === reasonShape);
}

function maybeEscalateExhaustedPlanQualityNeedsReplan(project_id, item) {
  if (!item || item.status !== 'needs_replan') {
    return { workItem: item, escalated: false };
  }

  const origin = getWorkItemOriginObject(item) || {};
  const reason = item.reject_reason || origin.last_rejection_reason || '';
  const reasonShape = normalizeRejectionReasonForShape(reason);
  const attempt = getPlanQualityReplanAttemptCount(item, origin);
  if (!shouldEscalatePlanQualityAttemptWindow({ reasonShape, attempt, origin })) {
    return { workItem: item, escalated: false };
  }

  const routed = routeWorkItemToNeedsReplan(item, {
    reason,
    attempt,
    details: {
      escalated_without_reexecution: true,
      prior_attempt_count: attempt,
    },
  });

  safeLogDecision({
    project_id,
    stage: LOOP_STATES.PRIORITIZE,
    action: 'plan_quality_attempt_window_escalated',
    reasoning: 'PRIORITIZE found a needs_replan item whose recorded plan-quality attempts already cross the same-shape threshold; escalating before another execution loop.',
    outcome: {
      ...getWorkItemDecisionContext(routed || item),
      previous_status: item.status,
      next_status: routed?.status || item.status,
      attempt_count: attempt,
      reason_shape: reasonShape,
    },
    confidence: 1,
  });

  return { workItem: routed || item, escalated: Boolean(routed) };
}

