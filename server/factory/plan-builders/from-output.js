// Plan-from-output builders: parse architect outputs back into structured
// plan tasks. Two recognition shapes are supported:
//   1. JSON `file_edits` proposals (diffusion-style structured output)
//   2. Numbered task summaries (free-form prose with "Task N:" headings)
//
// Plus a handful of pure string/array helpers used by both pipelines:
// fence unwrapping, prompt-echo trimming, indentation, and operation
// type normalization.
//
// Extracted from server/factory/loop-controller.js as part of Phase 1a.
// Behavior preserved; no signature changes.

const {
  inferAutoGeneratedPlanValidationCommand,
  inferAutoGeneratedPlanTechStack,
  slugifyAutoGeneratedPlanSegment,
  extractPlanDescriptionFilePaths,
} = require('../shared/plan-path');
const {
  formatPlanDescriptionFileList,
  buildTaskValidationDetail,
} = require('./task-spec');

function unwrapWholeMarkdownFence(value) {
  const trimmed = String(value || '').trim();
  const match = trimmed.match(/^```(?:[a-z0-9_-]+)?\r?\n([\s\S]*?)\r?\n```$/i);
  return match ? match[1].trim() : trimmed;
}

function convertFencedBlocksToIndented(value) {
  const lines = String(value || '').split(/\r?\n/);
  const converted = [];
  let inFence = false;

  for (const line of lines) {
    if (line.trim().startsWith('```')) {
      inFence = !inFence;
      continue;
    }

    if (inFence) {
      converted.push(line.length > 0 ? `    ${line}` : '');
      continue;
    }

    converted.push(line);
  }

  return converted.join('\n');
}

function isPromptEchoTail(lines, index) {
  const tail = lines.slice(index, Math.min(lines.length, index + 30)).join('\n');
  return /Use `## Task N:` headings exactly|Every task body MUST include all five|Project context:|Work item context:|Code-graph research:|Quality Rules/i.test(tail);
}

function trimPromptEchoTail(value) {
  const lines = String(value || '').split(/\r?\n/);
  const cutoff = lines.findIndex((line, index) => {
    if (index === 0) return false;
    const trimmed = line.trim();
    if (/^(Project context:|Work item context:|Code-graph research:)$/i.test(trimmed)) {
      return true;
    }
    if (/^#{1,3}\s+Quality Rules\b/i.test(trimmed)) {
      return true;
    }
    if (/^Every task body MUST include all five/i.test(trimmed)) {
      return true;
    }
    return trimmed === 'Rules:' && isPromptEchoTail(lines, index);
  });

  if (cutoff === -1) return value;
  return lines.slice(0, cutoff).join('\n').trimEnd();
}

function indentForPlan(value, spaces = 8) {
  const prefix = ' '.repeat(spaces);
  const text = String(value ?? '');
  if (!text) return `${prefix}<empty>`;
  return text.split(/\r?\n/).map((line) => `${prefix}${line}`).join('\n');
}

function normalizeProposalOperationType(operation) {
  const raw = typeof operation?.type === 'string' ? operation.type.trim().toLowerCase() : '';
  if (raw === 'create') return 'create';
  if (raw === 'delete') return 'delete';
  return 'replace';
}

function buildPlanFromFileEditsProposal(rawOutput, workItem, project) {
  let parsed;
  let validation;
  try {
    const computeParser = require('../../diffusion/compute-output-parser');
    parsed = computeParser.parseComputeOutput(rawOutput);
    validation = computeParser.validateComputeSchema(parsed);
  } catch (_err) {
    return null;
  }

  if (!parsed || !validation?.valid) {
    return null;
  }

  const edits = parsed.file_edits
    .map((edit) => ({
      file: String(edit.file || '').trim(),
      operations: Array.isArray(edit.operations) ? edit.operations : [],
    }))
    .filter((edit) => edit.file && edit.operations.length > 0);
  if (edits.length === 0) {
    return null;
  }

  const operationCount = edits.reduce((sum, edit) => sum + edit.operations.length, 0);
  const validationCommand = inferAutoGeneratedPlanValidationCommand(project?.path);
  const title = `${workItem?.title || `Work Item ${workItem?.id}`} Plan`;
  const lines = [
    `# ${title}`,
    '',
    `**Source:** auto-generated from work_item #${workItem?.id}`,
    '**Proposal Format:** normalized from file_edits JSON emitted by plan generation.',
    `**Tech Stack:** ${inferAutoGeneratedPlanTechStack(project?.path)}`,
    '',
    `## Task 1: Apply proposed edits for ${workItem?.title || `work item ${workItem?.id}`}`,
    '',
    '- [ ] **Step 1: Apply proposed repository edits**',
    '',
    `    Edit ${edits.length} file(s) with ${operationCount} exact operation(s). Scope is limited to ${edits.map((edit) => `\`${edit.file}\``).join(', ')}. Acceptance criteria: apply only the listed create/replace/delete operations, preserve unrelated code, and ensure the requested work item behavior is represented in the touched files.`,
    '',
  ];

  for (const edit of edits) {
    lines.push(`    File: \`${edit.file}\``);
    edit.operations.forEach((operation, index) => {
      const type = normalizeProposalOperationType(operation);
      lines.push(`    Operation ${index + 1}: ${type}`);
      if (type !== 'create') {
        lines.push('    Old text:');
        lines.push(indentForPlan(operation.old_text, 8));
      }
      if (type !== 'delete') {
        lines.push('    New text:');
        lines.push(indentForPlan(operation.new_text, 8));
      }
      lines.push('');
    });
  }

  lines.push(
    '- [ ] **Step 2: Validate changed area**',
    '',
    `    Run \`${validationCommand}\` from the repository root. The command should pass, or the worker must report a concrete pre-existing environment blocker tied to the touched files.`,
    '',
    '- [ ] **Step 3: Commit**',
    '',
    `    git commit -m "fix(${slugifyAutoGeneratedPlanSegment(project?.name || 'factory')}): ${slugifyAutoGeneratedPlanSegment(workItem?.title || 'apply proposal')}"`,
    '',
  );

  const plan = lines.join('\n').replace(/\n{3,}/g, '\n\n').trim();
  return plan.length <= 100000 ? `${plan}\n` : null;
}

function cleanNumberedPlanSummaryText(value) {
  return String(value || '')
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.;:)])/g, '$1')
    .replace(/^[\s:—–-]+/, '')
    .trim();
}

function extractNumberedPlanSummaryTasks(rawOutput) {
  const lines = String(rawOutput || '').split(/\r?\n/);
  const tasks = [];
  let current = null;

  const flushCurrent = () => {
    if (!current) return;
    current.detail = cleanNumberedPlanSummaryText(current.detail);
    current.explicitTitle = cleanNumberedPlanSummaryText(current.explicitTitle);
    if (current.detail) {
      tasks.push(current);
    }
    current = null;
  };

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    if (isPromptEchoTail(lines, index)) {
      break;
    }

    const numberedMatch = line.match(/^\s*(\d+)[.)]\s+(?:\*\*)?\s*Task\s+(\d+)(?:\s*[:.-]\s*([^*—–-]+?))?\s*(?:\*\*)?\s*(?:[—–-]\s*|:\s*)?(.*)$/i);
    const bareTaskMatch = numberedMatch
      ? null
      : line.match(/^\s*(?:[-*]\s*)?(?:\*\*)?\s*Task\s+(\d+)(?:\s*[:.-]\s*([^*—–-]+?))?\s*(?:\*\*)?\s*(?:[—–-]\s*|:\s*)?(.*)$/i);
    const match = numberedMatch || bareTaskMatch;
    if (match) {
      flushCurrent();
      current = {
        listNumber: numberedMatch ? Number(match[1]) : tasks.length + 1,
        taskNumber: Number(numberedMatch ? match[2] : match[1]),
        explicitTitle: numberedMatch ? (match[3] || '') : (match[2] || ''),
        detail: numberedMatch ? (match[4] || '') : (match[3] || ''),
      };
      continue;
    }

    if (!current) {
      continue;
    }

    const trimmed = line.trim();
    if (!trimmed) {
      continue;
    }
    if (/^(?:rules|project context|work item context|description|quality rules):$/i.test(trimmed)) {
      break;
    }
    if (/^\d+[.)]\s+/.test(trimmed)) {
      flushCurrent();
      continue;
    }
    current.detail = `${current.detail} ${trimmed}`;
  }

  flushCurrent();
  return tasks
    .filter((task, index) => {
      if (!Number.isFinite(task.taskNumber) || task.taskNumber <= 0) return false;
      if (task.listNumber !== index + 1 && task.taskNumber !== index + 1) return false;
      return extractPlanDescriptionFilePaths(`${task.explicitTitle}\n${task.detail}`).length > 0;
    })
    .slice(0, 5);
}

function titleFromNumberedPlanSummaryTask(task) {
  const explicit = cleanNumberedPlanSummaryText(task.explicitTitle);
  if (explicit) {
    return explicit.slice(0, 120);
  }

  let title = cleanNumberedPlanSummaryText(task.detail)
    .replace(/\([^)]*\)\s*$/g, '')
    .replace(/^\d+\s+/, '')
    .trim();
  if (/\btests?\b/i.test(title) && !/^(?:add(?:s|ed|ing)?|cover(?:s|ed|ing)?|create(?:s|d|ing)?|test(?:s|ed|ing)?|validate(?:s|d|ing)?)\b/i.test(title)) {
    title = `Add ${title}`;
  } else if (!/^(?:add(?:s|ed|ing)?|cover(?:s|ed|ing)?|create(?:s|d|ing)?|fix(?:es|ed|ing)?|harden(?:s|ed|ing)?|implement(?:s|ed|ing)?|persist(?:s|ed|ing)?|refactor(?:s|ed|ing)?|repair(?:s|ed|ing)?|test(?:s|ed|ing)?|validate(?:s|d|ing)?|wire(?:s|d|ing)?)\b/i.test(title)) {
    title = `Implement ${title}`;
  }
  return (title || `Plan task ${task.taskNumber}`).slice(0, 120).trim();
}

function summarizeNumberedPlanTaskScope(task, filePaths) {
  const detail = `${task.explicitTitle || ''}\n${task.detail || ''}`;
  const countMatch = detail.match(/\b(?:\d+|one|two|three|four|five)\s+(?:files?|lines?|tests?|cases?|branches?|paths?|commands?|changes?)\b/i);
  const fileCount = `${filePaths.length} file${filePaths.length === 1 ? '' : 's'}`;
  return countMatch ? `${countMatch[0]} across ${fileCount}` : `single focused change across ${fileCount}`;
}

function buildPlanFromNumberedTaskSummary(rawOutput, workItem, project) {
  const tasks = extractNumberedPlanSummaryTasks(rawOutput);
  if (tasks.length === 0) {
    return null;
  }

  const lines = [
    `# ${workItem?.title || `Work Item ${workItem?.id}`} Plan`,
    '',
    `**Source:** auto-generated from work_item #${workItem?.id}`,
    '**Plan Format:** normalized from numbered task summary emitted by plan generation.',
    `**Tech Stack:** ${inferAutoGeneratedPlanTechStack(project?.path)}`,
    '',
  ];

  tasks.forEach((task, index) => {
    const title = titleFromNumberedPlanSummaryTask(task);
    const rawPaths = extractPlanDescriptionFilePaths(`${task.explicitTitle}\n${task.detail}`);
    const files = [...new Set(rawPaths)].slice(0, 6);
    const fileList = formatPlanDescriptionFileList(files, 6) || 'the scoped project files';
    const scope = summarizeNumberedPlanTaskScope(task, files);
    const detail = cleanNumberedPlanSummaryText(task.detail || title);
    const validationTask = {
      title,
      body: `${detail}\n${files.map((file) => `\`${file}\``).join(' ')}`,
    };
    const validation = buildTaskValidationDetail(validationTask, workItem, project, files);

    lines.push(
      `## Task ${index + 1}: ${title}`,
      '',
      '- [ ] **Step 1: Implement the generated plan item**',
      '',
      `    Edit ${fileList}. Estimated scope: ${scope}. Acceptance criteria: ${detail}. The change must satisfy only this generated plan item and leave unrelated behavior unchanged.`,
      '',
      '- [ ] **Step 2: Validate targeted change**',
      '',
      `    Run \`${validation}\` from the repository root. Success criteria: the command should pass for ${fileList}, or the worker must report a concrete pre-existing blocker tied to those files.`,
      '',
    );
  });

  const plan = lines.join('\n').replace(/\n{3,}/g, '\n\n').trim();
  return plan.length <= 100000 ? `${plan}\n` : null;
}

