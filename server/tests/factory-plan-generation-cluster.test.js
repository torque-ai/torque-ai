import { describe, it, expect } from 'vitest';
import {
  createPlanGenerationCluster,
  PLAN_GENERATOR_LABEL,
  WORK_ITEM_STATUS_ORDER,
} from '../factory/plan-generation-cluster.js';

// Phase 3 slice 5 re-scope (3c): the plan-generation cluster (71 functions:
// 25 referenced by loop-controller's PLAN/EXECUTE block + 46 cluster-internal
// fold-ins) moved from loop-controller.js to plan-generation-cluster.js.
// Behavioral coverage stays in the loop-controller factory tests. This file
// pins the createPlanGenerationCluster dependency-injection contract.

const FN_DEPS = [
  'augmentAutoGeneratedTaskSpecificity', 'extractCodexFinalAnswerFromTranscript',
  'extractTextContent', 'getDecisionBatchId', 'getDefaultFactoryBatchId', 'getTaskMetadataObject',
  'getWorkItemDecisionContext', 'getWorktreeRunner', 'hasObjectLevelDetail', 'isAutoGeneratedPlanPath',
  'isSchedulerOwnedPlanGenerationTask', 'isStaleNeverStartedPendingPlanGenerationTask',
  'looksLikeDirectPlanMarkdown', 'normalizeOptionalString', 'normalizeTaskTags', 'normalizeWorkItemId',
  'nowIso', 'parseJsonObject', 'rememberSelectedWorkItem', 'safeLogDecision',
  'scoreAutoGeneratedPlanDescriptions',
  // Cross-cluster worktree-owner deps (3b).
  'ensureReusedFactoryWorktreeFresh', 'factoryWorktreeBelongsToWorkItem', 'getFactoryWorktreePath',
  'getFactoryWorktreeWorkItemId', 'prepareReusedFactoryWorktreeDependencies',
];

function makeFullDeps() {
  const deps = {};
  for (const name of FN_DEPS) deps[name] = () => {};
  return deps;
}

describe('createPlanGenerationCluster — dependency-injection contract', () => {
  it('returns the 25 externally-used plan-generation functions with full deps', () => {
    const api = createPlanGenerationCluster(makeFullDeps());
    expect(Object.keys(api)).toHaveLength(25);
    for (const fn of Object.values(api)) expect(typeof fn).toBe('function');
    expect(typeof api.reviewAutoGeneratedPlan).toBe('function');
    expect(typeof api.findExistingPlanTaskSubmission).toBe('function');
    expect(typeof api.getPlanGenerationTask).toBe('function');
  });

  it('throws naming each missing function dep', () => {
    for (const missing of FN_DEPS) {
      const deps = makeFullDeps();
      delete deps[missing];
      expect(() => createPlanGenerationCluster(deps)).toThrow(new RegExp(`dep '${missing}' is required`));
    }
  });

  it('throws when called with no deps at all', () => {
    expect(() => createPlanGenerationCluster()).toThrow(/is required/);
  });

  it('re-exports the plan-generation constants loop-controller still needs', () => {
    expect(PLAN_GENERATOR_LABEL).toBe('auto-router');
    expect(Array.isArray(WORK_ITEM_STATUS_ORDER)).toBe(true);
    expect(Object.isFrozen(WORK_ITEM_STATUS_ORDER)).toBe(true);
  });
});
